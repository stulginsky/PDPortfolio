import { createHash } from 'node:crypto'
import { promises as fs } from 'node:fs'
import path from 'node:path'

const projectRoot = process.cwd()
const publicRoot = path.join(projectRoot, 'public')
const outputPath = path.join(projectRoot, 'app', 'generated', 'public-asset-revisions.ts')
const checkOnly = process.argv.includes('--check')

async function collectFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const absolutePath = path.join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await collectFiles(absolutePath))
    else if (entry.isFile()) files.push(absolutePath)
  }

  return files
}

function publicPath(absolutePath) {
  return `/${path.relative(publicRoot, absolutePath).split(path.sep).join('/')}`
}

const files = (await collectFiles(publicRoot)).sort((left, right) => publicPath(left).localeCompare(publicPath(right)))
const revisions = {}

for (const file of files) {
  const contents = await fs.readFile(file)
  revisions[publicPath(file)] = createHash('sha256').update(contents).digest('hex').slice(0, 12)
}

const generated = `// Generated by scripts/generate-public-asset-revisions.mjs. Do not edit manually.\n` +
  `// Every public file has an independent content revision for stable cache invalidation.\n` +
  `export const publicAssetRevisions: Readonly<Record<string, string>> = ${JSON.stringify(revisions, null, 2)}\n`

let current = ''
try {
  current = await fs.readFile(outputPath, 'utf8')
} catch (error) {
  if (error?.code !== 'ENOENT') throw error
}

if (checkOnly) {
  if (current !== generated) {
    console.error('Public asset revision manifest is stale. Run npm run generate:asset-revisions.')
    process.exitCode = 1
  } else {
    console.log(`Public asset revision manifest is current (${files.length} files).`)
  }
} else if (current === generated) {
  console.log(`Public asset revision manifest is unchanged (${files.length} files).`)
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true })
  await fs.writeFile(outputPath, generated, 'utf8')
  console.log(`Generated public asset revisions for ${files.length} files.`)
}
