import fs from 'node:fs'
import assert from 'node:assert/strict'
import { chromium } from 'playwright'

const browser = await chromium.launch({ headless: true })
const results = []
try {
  const page = await browser.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  for (const width of [296, 320, 370, 425, 462, 768, 1024, 1920]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('http://127.0.0.1:6006/iframe.html?id=compositions-showcase-cards-dcpickerapp-ux--sandbox&viewMode=story&embed=true')
    const card = page.locator('.dc-picker-app-ux')
    await card.waitFor()
    await page.evaluate(async () => {
      const title = document.querySelector('h2')
      const style = getComputedStyle(title)
      await document.fonts.load(`${style.fontWeight} ${style.fontSize} ${style.fontFamily}`, 'Picker')
      await document.fonts.ready
    })
    const box = await card.boundingBox()
    const button = card.locator('a')
    const image = button.locator('img')
    await image.evaluate(i => i.decode())
    const titleImage = card.locator('.dc-picker-app-ux__title')
    await titleImage.evaluate(i => i.decode())
    const titleBox = await titleImage.boundingBox()
    const nominal=Math.min(430,width-32),scale=Math.min(1,box.width/nominal)
    assert(Math.abs(titleBox.x-box.x-(box.width/2-(width>=462?84.419921875:84.03125)*scale))<.1)
    assert(Math.abs(titleBox.y-box.y-(width>=462?194.35546875:146.35546875))<.1)
    assert(Math.abs(titleBox.width-173*scale)<.1)
    const b = await button.boundingBox()
    assert.equal(box.height,width>=462?532:500)
    assert(Math.abs(b.width-98)<.1)
    assert.equal(await card.locator('.dc-picker-app-ux__badges li').count(),7)
    for(const badge of await card.locator('.dc-picker-app-ux__badges li').all()){
      const r=await badge.boundingBox();assert(r.x>=box.x&&r.x+r.width<=box.x+box.width+.1&&r.y+r.height<=box.y+box.height)
    }
    assert.equal(await card.locator('a').count(), 1)
    assert.equal(await card.getAttribute('href'), null)
    const uri = new URL(await button.getAttribute('href'))
    assert.equal(uri.protocol, 'mailto:')
    assert.equal(uri.pathname, 'stulginsky@gmail.com')
    assert.equal(uri.searchParams.get('subject'), 'Сообщите о новом кейсе')
    assert.equal(uri.searchParams.get('body'), 'Привет, Константин! Очень хочу посмотреть новый кейс Picker App. Сообщите о публикации. Спасибо.')
    await button.hover()
    const tooltip = card.getByRole('tooltip')
    await tooltip.waitFor()
    assert.match(await tooltip.innerText(), /Подписаться/)
    assert.equal(await button.getAttribute('aria-describedby'), await tooltip.getAttribute('id'))
    const hint = await tooltip.boundingBox()
    assert(hint.x >= box.x - 1)
    assert(hint.x + hint.width <= b.x + 1)
    if (width === 462 || width === 320) await card.screenshot({ path: `E:/GitHub/PDPortfolio-DS/ds/evidence/dc-picker-app-ux-${width}-hover.png` })
    await page.waitForTimeout(180)
    const hover = await button.evaluate(e => getComputedStyle(e).filter)
    assert(!hover.includes('rgba(0, 0, 0, 0)'), hover)
    await page.mouse.down()
    const pressed = await button.evaluate(e => getComputedStyle(e).filter)
    assert(pressed.includes('rgba(0, 0, 0, 0)'), pressed)
    await page.mouse.up()
    await button.evaluate(e => e.blur())
    await page.mouse.move(0, 850)
    await page.waitForTimeout(330)
    assert.equal(await tooltip.count(), 0)
    await button.focus()
    await tooltip.waitFor()
    assert.equal(await button.evaluate(e => document.activeElement === e), true)
    assert.equal(await tooltip.count(), 1)
    await page.keyboard.press('Tab')
    if (width === 462 || width === 320) {
      await page.mouse.move(0, 850)
      await card.screenshot({ path: `E:/GitHub/PDPortfolio-DS/ds/evidence/dc-picker-app-ux-${width}.png` })
    }
    results.push({ viewport: width, width: box.width, height: box.height, button: b.width, hover, pressed })
  }
  await page.emulateMedia({ reducedMotion: 'reduce' })
  assert.equal(await page.locator('.ds-coming-soon').evaluate(e => getComputedStyle(e).transitionDuration), '0s')
  await page.addScriptTag({ path: new URL('../node_modules/axe-core/axe.js', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1') })
  const violations = await page.evaluate(async () => (await axe.run('.dc-picker-app-ux')).violations.map(v => ({ id: v.id, impact: v.impact })))
  assert.deepEqual(violations, [])
  const touchContext = await browser.newContext({ hasTouch: true, isMobile: true, viewport: { width: 320, height: 812 } })
  const touchPage = await touchContext.newPage()
  await touchPage.goto('http://127.0.0.1:6006/iframe.html?id=compositions-showcase-cards-dcpickerapp-ux--sandbox&viewMode=story&embed=true')
  const touchLink = touchPage.locator('.ds-coming-soon')
  await touchLink.waitFor()
  await touchLink.tap()
  assert.equal(await touchLink.evaluate(e => getComputedStyle(e).filter.includes('rgba(0, 0, 0, 0)')), true)
  await touchContext.close()
  assert.deepEqual(errors, [])
  fs.writeFileSync('E:/GitHub/PDPortfolio-DS/ds/evidence/dc-picker-app-ux-verification.json', JSON.stringify({ results, errors, reducedMotion: true, violations }, null, 2))
  console.log('PASS:8 widths, geometry, original image decode, mail draft, hover/press/focus, reduced motion, no page errors')
} finally { await browser.close() }
